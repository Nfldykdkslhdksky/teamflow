create or replace function public.update_workspace_task_status(task_id bigint, new_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new_status not in ('To do', 'In progress', 'In review', 'Completed') then
    raise exception 'Invalid task status';
  end if;

  update public.workspace_tasks
  set status = new_status,
      completion_percentage = case
        when new_status = 'Completed' then 100
        when new_status = 'To do' then 0
        else completion_percentage
      end,
      updated_at = now()
  where id = task_id
    and (
      assignee_id = (select auth.uid())
      or (select public.is_workspace_admin())
    );

  if not found then
    raise exception 'Task not found or not assigned to the current user';
  end if;
end;
$$;

revoke all on function public.update_workspace_task_status(bigint, text) from public;
grant execute on function public.update_workspace_task_status(bigint, text) to authenticated;

